"""Adds the Firebase Gradle plugins to Godot's Android build template (android/build).

android/ is generated by "Install Android Build Template" and is git-ignored, so run this after
(re)installing the template. Safe to run any number of times.

Firebase is only switched on when android/build/google-services.json exists (download it from the
Firebase console, see docs/FIREBASE_SETUP.md). Without the file builds work and send nothing.

Run: python3 tools/patch_android_template.py
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILD = os.path.join(ROOT, "android", "build")
MARK = "// castle-smashers: firebase"

# Legacy buildscript classpath so the plugins can be applied conditionally below.
CLASSPATH_ADD = """// castle-smashers: firebase classpath
buildscript {
    repositories { google(); mavenCentral() }
    dependencies {
        classpath 'com.google.gms:google-services:4.4.4'
        classpath 'com.google.firebase:firebase-crashlytics-gradle:3.0.6'
    }
}

"""

# Earlier patch versions, upgraded in place to the set GodotX Firebase (push) is built against.
UPGRADES = [
    ("classpath 'com.google.gms:google-services:4.4.2'", "classpath 'com.google.gms:google-services:4.4.4'"),
    ("classpath 'com.google.firebase:firebase-crashlytics-gradle:3.0.2'", "classpath 'com.google.firebase:firebase-crashlytics-gradle:3.0.6'"),
]

APP_ADD = """
// castle-smashers: firebase (only when google-services.json is present)
if (file('google-services.json').exists()) {
    apply plugin: 'com.google.gms.google-services'
    apply plugin: 'com.google.firebase.crashlytics'
}
"""


def unpatch_settings(path):
    """Removes the first version of this patch (plugin ids in settings.gradle)."""
    with open(path) as fh:
        lines = fh.readlines()
    kept = [l for l in lines if MARK not in l]
    if len(kept) != len(lines):
        with open(path, "w") as fh:
            fh.writelines(kept)


def patch(path, anchor, text, after=True, mark=MARK):
    with open(path) as fh:
        src = fh.read()
    if mark in src:
        return False
    i = src.find(anchor)
    if i < 0:
        sys.exit(f"patch_android_template: '{anchor.strip()}' not found in {path}")
    j = i + len(anchor) if after else i
    with open(path, "w") as fh:
        fh.write(src[:j] + text + src[j:])
    return True


SPLASH_NONE = """<?xml version="1.0" encoding="utf-8"?>
<!-- castle-smashers: no splash icon, the studio intro is the first thing players see -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="#00000000" />
</shape>
"""


def patch_splash():
    """Android 12+ launch splash: plain black instead of the painted icon background."""
    with open(os.path.join(BUILD, "res", "drawable", "cs_splash_none.xml"), "w") as fh:
        fh.write(SPLASH_NONE)
    path = os.path.join(BUILD, "res", "values", "themes.xml")
    with open(path) as fh:
        src = fh.read()
    new = src.replace('<item name="android:windowSplashScreenBackground">@mipmap/icon_background</item>',
                      '<item name="android:windowSplashScreenBackground">@android:color/black</item>')
    new = new.replace('<item name="windowSplashScreenAnimatedIcon">@drawable/splash_icon</item>',
                      '<item name="windowSplashScreenAnimatedIcon">@drawable/cs_splash_none</item>')
    with open(path, "w") as fh:
        fh.write(new)
    return "patched" if new != src else "already patched"


BACKUP_RULES = """<?xml version="1.0" encoding="utf-8"?>
<!-- castle-smashers: Android 11 and older. Back up only the player's progress file (user://save.json). -->
<full-backup-content>
    <include domain="file" path="save.json" />
</full-backup-content>
"""

DATA_RULES = """<?xml version="1.0" encoding="utf-8"?>
<!-- castle-smashers: Android 12+. Google Drive backup and phone-to-phone transfer of the progress file only.
     Ads, Firebase and billing caches are never restored, so IDs are not cloned between devices. -->
<data-extraction-rules>
    <cloud-backup>
        <include domain="file" path="save.json" />
    </cloud-backup>
    <device-transfer>
        <include domain="file" path="save.json" />
    </device-transfer>
</data-extraction-rules>
"""


def patch_backup():
    """Android Auto Backup of the save file (turn on with user_data_backup/allow=true in export_presets.cfg)."""
    xml = os.path.join(BUILD, "res", "xml")
    os.makedirs(xml, exist_ok=True)
    for name, text in (("cs_backup_rules.xml", BACKUP_RULES), ("cs_data_rules.xml", DATA_RULES)):
        with open(os.path.join(xml, name), "w") as fh:
            fh.write(text)
    path = os.path.join(BUILD, "src", "main", "AndroidManifest.xml")
    with open(path) as fh:
        src = fh.read()
    if "cs_data_rules" in src:
        return "already patched"
    anchor = 'android:allowBackup="false"'
    if anchor not in src:
        sys.exit("patch_android_template: allowBackup not found in " + path)
    new = src.replace(anchor, anchor + '\n        android:fullBackupContent="@xml/cs_backup_rules"\n        android:dataExtractionRules="@xml/cs_data_rules"', 1)
    with open(path, "w") as fh:
        fh.write(new)
    return "patched"


def main():
    if not os.path.isdir(BUILD):
        sys.exit("android/build not found: install the Android build template from Godot first")
    unpatch_settings(os.path.join(BUILD, "settings.gradle"))
    gradle = os.path.join(BUILD, "build.gradle")
    c = patch(gradle, "// Gradle build config for Godot Engine's Android port.\n", CLASSPATH_ADD, mark="firebase classpath")
    a = patch(gradle, "apply from: 'config.gradle'\n", APP_ADD, mark="only when google-services.json")
    print("classpath", "patched" if c else "already patched")
    with open(gradle) as fh:
        src = fh.read()
    up = src
    for old, new in UPGRADES:
        up = up.replace(old, new)
    if up != src:
        with open(gradle, "w") as fh:
            fh.write(up)
        print("classpath versions upgraded")
    print("splash", patch_splash())
    print("backup rules", patch_backup())
    print("build.gradle", "patched" if a else "already patched")
    have = os.path.exists(os.path.join(BUILD, "google-services.json"))
    print("google-services.json:", "found (Firebase ON)" if have else "missing (Firebase OFF until you add it)")


if __name__ == "__main__":
    main()
